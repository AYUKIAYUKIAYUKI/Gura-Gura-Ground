// 選択中の障害物
CObstacle* CObstacle::s_pPickingObstacle = nullptr;

//============================================================================
// デフォルトコンストラクタ
//============================================================================
CObstacle::CObstacle(OBJ::TYPE Type, OBJ::LAYER Layer, Obstacle::OBSTACLE_TYPE ObsType)
	: CPhysicsModel(Type, Layer)
	, m_ObsType(ObsType)
{}

//============================================================================
// デストラクタ
//============================================================================
CObstacle::~CObstacle()
{}

//============================================================================
// 更新
//============================================================================
void CObstacle::Update()
{
	// 物理モデル用の更新処理
	CPhysicsModel::Update();
}

//============================================================================
// 描画
//============================================================================
void CObstacle::Draw()
{
	// 物理モデル用の描画処理
	CPhysicsModel::Draw();
}

//============================================================================
// インスペクターの表示
//============================================================================
void CObstacle::ShowInspector()
{
	useful::MIS::MyImGuiShortcut_BeginWindow("Inspector");
	ImGui::Text(reinterpret_cast<const char*>(u8"この障害物はインスペクターの表示をオーバーライドしていません"));
	ImGui::End();
}

//============================================================================
// パラメータの編集
//============================================================================
void CObstacle::EditParam()
{}

//============================================================================
// 選択中の障害物をバインド
//============================================================================
void CObstacle::BindPickingObstacle(CObstacle* pObstacle)
{
	if (!pObstacle)
	{
		return;
	}

	s_pPickingObstacle = pObstacle;
}

//============================================================================
// 選択中の障害物の更新
//============================================================================
void CObstacle::UpdatePickingObstacle()
{
	if (!s_pPickingObstacle)
	{
		return;
	}

	s_pPickingObstacle->ShowInspector();
}